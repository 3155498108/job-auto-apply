def safe(s):
    return re.sub(r'[\\/:*?"<>|]', "", s or "").replace(" ", "")[:26]


def read_archived(folder):
    """读原归档话术的正文与段落标签（证据必须来自原话术，不新增事实）。"""
    fp = os.path.join(RECRUIT, folder, "新建 文本文档.txt")
    if not os.path.isfile(fp):
        return "", ""
    txt = io.open(fp, encoding="utf-8").read()
    m = re.search(r"【主推版[^\n]*】\s*\n(.*?)(?=\n【|\n={5,}|\n-{5,}|\Z)", txt, re.S)
    body = ""
    if m:
        t = m.group(1).replace("**", "").replace("`", "")
        t = re.sub(r"^\s*[-*>]\s*|^\s*\d+\.\s*|^#+\s*", "", t, flags=re.M)
        body = "\n".join(ln.strip() for ln in t.splitlines() if ln.strip())
    labels = re.findall(r"【([^】]+)】", body)
    return body, labels


def pick_evidence(labels):
    for lb in labels:
        if lb in EVIDENCE:
            return EVIDENCE[lb]
    return DEFAULT_EV


def main():
    tf = sys.argv[1] if len(sys.argv) > 1 else "resend_targets.json"
    targets = json.load(io.open(os.path.join(WORK, tf), encoding="utf-8"))
    out = []
    used_names = {}
    for i, t in enumerate(targets):
        folder = t.get("folder", "")
        body, labels = read_archived(folder)
        ev_body, ev_tpls = pick_evidence(labels)
        comp = t.get("company", "")
        pos = t.get("position", "")
        opener = OPENERS[i % len(OPENERS)]
        ending = ENDINGS[(i * 7 + 3) % len(ENDINGS)]
        extra = EXTRA[(i * 3 + 1) % len(EXTRA)]
        ev = ev_tpls[i % len(ev_tpls)]
        text = (f"{opener}\n"
                f"**【能对上的地方】**{ev}。\n"
                f"{extra}{ending}")
        # 同公司同岗位可能出现多个 HR → 目录名要唯一，否则会互相覆盖
        base = f"{PREFIX}-{safe(comp)}-{safe(pos)}-{safe(t.get('city',''))}"
        n = used_names.get(base, 0)
        used_names[base] = n + 1
        label = base if n == 0 else f"{base}-{n + 1}"
        d = os.path.join(RECRUIT, label)
        os.makedirs(d, exist_ok=True)
        content = (f"{comp} · {pos}\n"
                   f"地址：{t.get('city','')}\n"
                   f"薪资：{t.get('salary','')}\n\n"
                   f"【主推版 · 第二次触达 · {len(text)} 字】\n{text}\n\n"
                   f"【精简版 · {len(text)} 字】\n{text}\n\n"
                   f"【证据来源】\n"
                   f"- 取自首次投递的话术目录：{folder}\n"
                   f"- 沿用其中的证据段落：{'/'.join(labels[:2]) or '-'}\n"
                   f"- 未新增任何技术或数字\n")
        with io.open(os.path.join(d, "新建 文本文档.txt"), "w", encoding="utf-8") as f:
            f.write(content)
        out.append(dict(label=label, folder=label, jobId=t.get("jobId", ""),
                        city=t.get("city", ""), company=comp, position=pos,
                        salary=t.get("salary", ""), tpl="第二次触达",
                        evidence=ev, main_len=len(text), src_folder=folder,
                        days_since=t.get("days_since", "")))
    with io.open(os.path.join(WORK, "resend_final.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    print(f"生成 {len(out)} 条第二次触达话术 → resend_final.json")
    from collections import Counter
    print("证据变体分布:", dict(Counter(x["evidence"][:24] for x in out).most_common(8)))


main()
